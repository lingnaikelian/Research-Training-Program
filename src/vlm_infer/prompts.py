"""
行为识别 Prompt 模板。

核心设计：
- 只给模型看"一个人的裁剪图"，让它基于该人姿态判断行为
- 输出严格 JSON，字段固定，降低解析难度
- 明确告诉模型"不确定就填 0，不要臆测"（抑制幻觉）
"""

BEHAVIOR_PROMPT = """你是一位教室行为分析专家。图中是一个人（或空座位区域）的截取画面。

请根据画面中这个人的姿态，逐项判断以下 5 类行为是否正在发生，每项只能填 0 或 1：

1. sleeping：睡觉/打盹——**头部伏在桌面上**，或**坐姿低头且手部长时间不动**（没有书写、翻页、拿东西等任何手部动作，像闭眼休息）。仅低头但手部在动（书写/操作）不算
2. looking_phone：低头看手机（双手持手机或视线朝向手机屏幕）
3. looking_around：左右张望（头部频繁转动看向左右两侧，而非长时间注视一个方向）
4. talking：与人交谈（嘴巴张开说话，或侧头朝向旁边的人正在交流）
5. away：离座/离开座位区域——人物处于站立或走动状态，明显离开座位（如起身走向门口、背对镜头离开、走出画面）；或画面中只有空座位、没有人

规则：
- 判断依据只来自图中这个人的姿态，不要臆测图中看不到的信息
- 一个画面可以同时命中多个行为（如：一边看手机一边抬头张望），也可以全为 0
- 不确定时对应字段填 0
- 最后用一句话给出判断理由（reason），说明你看到了什么关键特征

必须严格输出以下 JSON 格式，不要输出任何其他文字：
{"sleeping": 0, "looking_phone": 0, "looking_around": 0, "talking": 0, "away": 0, "reason": "一句话理由"}
"""

# ===== 多帧版 Prompt（连续 3 帧拼接图，能看出动作变化）=====
MULTIFRAME_PROMPT = """你是一位教室行为分析专家。图中是**同一个人**连续 3 个时刻的画面，
按从左到右的时间顺序排列（第1格最早，第3格最晚）。

请结合 3 格画面的**动作变化**（而不只是静态姿态），逐项判断以下 5 类行为是否正在发生，
每项只能填 0 或 1：

1. sleeping：睡觉/打盹——**头部伏在桌面上**，或**坐姿低头且手部长时间不动**（没有书写、翻页、拿东西等任何手部动作，像闭眼休息）。仅低头但手部在动（书写/操作）不算
2. looking_phone：低头看手机（3 格中持续低头看手机屏幕）
3. looking_around：左右张望（3 格中**头部位置明显左右变化**，如在转头环顾四周）
4. talking：与人交谈（3 格中**嘴巴张开说话**，或侧头朝向旁边的人交流）
5. away：离座/离开座位（3 格中**人物从坐姿变为站立/走动**，或起身走向门口、背对镜头离开、走出画面；或画面中只有空座位）

重点提示：
- 张望和交谈必须看 3 格之间的**动作差异**，不要只看某一格的静态姿态
- sleeping 必须看到"头伏在桌面上"；只低头静止（如看书写字）不算睡觉
- 如果 3 格几乎没有变化且不是趴桌，各行为都填 0（正常静坐/学习）
- 不确定时对应字段填 0
- 最后用一句话给出判断理由（reason），说明你看到了什么关键动作

必须严格输出以下 JSON 格式，不要输出任何其他文字：
{"sleeping": 0, "looking_phone": 0, "looking_around": 0, "talking": 0, "away": 0, "reason": "一句话理由"}
"""

# ===== 双人联合区域多帧版 Prompt（6 帧 2x3 网格，能看多人互动与动作轨迹）=====
UNION_MULTIFRAME_PROMPT = """你是一位教室行为分析专家。图中是教室座位的**连续 6 个时刻**画面，
按时间顺序排列为 2 行 × 3 列（第一行从左到右是最早的第1~3格，第二行从左到右是第4~6格，整体时间从左到右、从上到下递增）。
画面可能包含**1 个或多个人**，重点关注**人与人的互动**和**动作随时间的变化**。

请结合 6 格画面的**动作变化**，逐项判断以下 5 类行为是否正在发生，每项只能填 0 或 1：

1. sleeping：有人趴桌睡觉（**头部伏在桌面上**，多格中一直保持该姿势不动）。仅低头静止但头未伏桌面不算
2. looking_phone：有人低头看手机（多格中持续低头看手机屏幕，手部持机）
3. looking_around：有人左右张望（多格中**头部明显左右转动**，如转头环顾四周、看向不同方向）
4. talking：有人正在与人交谈（**两人面对面或侧身相对，嘴巴张开说话**；或一人在听旁边人说话时侧头朝向对方）
5. away：有人离座（多格中**某人从坐姿变为站立/走动**，起身走向门口、背对镜头离开，或画面中座位已空）

关键区分（务必注意）：
- **交谈 vs 低头看手机 vs 低头写字**：如果画面中两个人**相对而坐、侧头朝向对方、嘴巴张开**，即使头部偏低，也判 talking；
  低头且手部持手机屏幕判 looking_phone；低头但手持笔书写判 0（正常学习），不要臆测成看手机。
- **离座**：必须看到"从坐着变成站着/走动"或"座位从有人变空"的**变化**，不能只看静态坐姿。
- **张望**：必须看到头部**左右转向不同方向**的变化。
- 不确定时对应字段填 0；6 格几乎无变化且非趴桌，各行为填 0（正常静坐/学习）。
- 最后用一句话给出判断理由（reason），说明你看到了什么关键动作和判断依据。

必须严格输出以下 JSON 格式，不要输出任何其他文字：
{"sleeping": 0, "looking_phone": 0, "looking_around": 0, "talking": 0, "away": 0, "reason": "一句话理由"}
"""

# ===== 简化版 Prompt（把判断权交给大模型，仅给定义与输出格式）=====
SIMPLE_PROMPT = """你是一位教室行为分析专家。图中是教室座位的**连续 6 个时刻**画面，
排列为 2 行 × 3 列（时间从左到右、从上到下递增），可能包含 1 个或多个人。

请观察 6 格之间的动作变化，用你的常识判断画面中正在发生哪些课堂行为，
从以下 5 类中选择（可多选，也可都不选，每项填 0 或 1）：

- sleeping：有人在睡觉或打盹（头伏在桌上，或低头闭眼长时间不动，手没有书写等动作）
- looking_phone：有人在看手机（低头看着手机屏幕，或手持手机）
- looking_around：有人在左右张望（头部转动看向不同方向）
- talking：有人在交谈（与旁边的人面对面说话，嘴巴张开或侧头朝向对方）
- away：有人离座（从坐姿起身走动、离开座位区域，或座位从有人变空）

提示：重点关注人物动作随时间的变化，而不是只看某一格的静态姿态。
不确定就填 0，不要臆测。

必须严格输出以下 JSON 格式，不要输出任何其他文字：
{"sleeping": 0, "looking_phone": 0, "looking_around": 0, "talking": 0, "away": 0, "reason": "一句话理由"}
"""


def build_prompt(multiframe: bool = False, union: bool = False,
                 simple: bool = False) -> str:
    """返回行为识别 prompt。

    simple=True 用简化版（只给定义+输出格式，判断权交给模型），优先级最高；
    union=True 用双人联合区域多帧版（crops_union）；
    multiframe=True 用多帧版（crops_multi 单人多帧）。
    """
    if simple:
        return SIMPLE_PROMPT
    if union:
        return UNION_MULTIFRAME_PROMPT
    return MULTIFRAME_PROMPT if multiframe else BEHAVIOR_PROMPT
